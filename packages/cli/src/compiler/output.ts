// Assembles the output folder's files (OUT-01, OUT-03, OUT-04) and writes them, touching only the
// files the compiler owns (OUT-02, CLI-03). Ownership is the `files` list of the previous
// manifest.json, so an unrelated file in the folder is never deleted.

import { createHash } from "node:crypto"
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmdirSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { dirname, join, sep } from "node:path"

import type { PlatformValues } from "@email-kit/core/internal"
import { DIALECT } from "@email-kit/dialect"

import { VERSION } from "../version.ts"
import { toJavaScript } from "./emit/javascript.ts"
import { generateModule, moduleHeader } from "./emit/module.ts"
import type { CompiledTemplate } from "./project.ts"

export interface OutputFile {
  /** Relative to the output folder, with `/` separators */
  readonly path: string
  readonly content: string
}

export interface WriteResult {
  readonly written: readonly string[]
  readonly unchanged: readonly string[]
  readonly deleted: readonly string[]
}

const GENERATED =
  "Generated by email-kit. Do not edit: change the templates and run `email-kit compile`."

/**
 * Every file of the output folder. The `.html` and `.txt` files are the exact email parts, so they
 * carry no header; manifest.json and schema.json carry it as `$comment`.
 */
export function buildOutput(
  templates: readonly CompiledTemplate[],
  options: {
    readonly locales: readonly string[]
    readonly configFile: string
    readonly module: "ts" | "mjs"
    readonly perTemplateEntries: boolean
    readonly validate: boolean
    readonly platform: PlatformValues
  },
): OutputFile[] {
  const files: OutputFile[] = []
  const manifestTemplates = templates.map((template) => {
    const { $schema, ...schema } = template.jsonSchema
    files.push({
      path: `${template.id}/schema.json`,
      content: json({ $schema, $comment: GENERATED, ...schema }),
    })
    const locales: Record<string, unknown> = {}
    for (const email of template.emails) {
      const html = { path: `${template.id}/${email.locale}.html`, content: email.html }
      const text = { path: `${template.id}/${email.locale}.txt`, content: email.text }
      files.push(html, text)
      locales[email.locale] = {
        subject: email.subject,
        preheader: email.preheader,
        html: describe(html),
        text: describe(text),
      }
    }
    return {
      id: template.id,
      purpose: template.purpose,
      property: template.identifiers.property,
      schema: `${template.id}/schema.json`,
      locales,
    }
  })
  const moduleOptions = {
    version: VERSION,
    locales: options.locales,
    configFile: options.configFile,
    context: options.platform.runtime,
    validate: options.validate,
  }
  // One module for every template, and optionally one per template (OUT-06): the same
  // generator on a single template, so every entry has the same API and is self-contained.
  const writeModule = (folder: string, included: readonly CompiledTemplate[]) => {
    const typescript = generateModule(included, moduleOptions)
    if (options.module === "mjs") {
      const { js, dts } = toJavaScript(typescript, moduleHeader(moduleOptions))
      files.push(
        { path: `${folder}index.mjs`, content: js },
        { path: `${folder}index.d.mts`, content: dts },
      )
    } else {
      files.push({ path: `${folder}index.ts`, content: typescript })
    }
  }
  writeModule("", templates)
  if (options.perTemplateEntries) {
    for (const template of templates) writeModule(`${template.id}/`, [template])
  }
  const owned = [...files.map((file) => file.path), "manifest.json"].sort()
  files.push({
    path: "manifest.json",
    content: json({
      $comment: GENERATED,
      schemaVersion: 1,
      emailKit: VERSION,
      dialect: DIALECT,
      profiles: { subject: "text", preheader: "text", html: "html", text: "text" },
      locales: options.locales,
      // Constants are written into the templates; runtime keys are passed to createEmails().
      platform: {
        constants: sortKeys(options.platform.constants),
        runtime: options.platform.runtime,
      },
      templates: manifestTemplates,
      files: owned,
    }),
  })
  return files.sort((a, b) => (a.path < b.path ? -1 : 1))
}

/** Writes the files, skipping unchanged ones, and deletes owned files that are no longer output. */
export function writeOutput(out: string, files: readonly OutputFile[]): WriteResult {
  const previous = ownedFiles(out)
  const next = new Set(files.map((file) => file.path))
  const deleted: string[] = []
  for (const path of previous) {
    if (next.has(path)) continue
    rmSync(join(out, ...path.split("/")), { force: true })
    deleted.push(path)
    removeEmptyParents(out, dirname(join(out, ...path.split("/"))))
  }
  const written: string[] = []
  const unchanged: string[] = []
  for (const file of files) {
    const target = join(out, ...file.path.split("/"))
    if (existsSync(target) && readFileSync(target, "utf8") === file.content) {
      unchanged.push(file.path)
      continue
    }
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, file.content)
    written.push(file.path)
  }
  return { written, unchanged, deleted }
}

// The `files` of the previous manifest, limited to safe relative paths inside the folder.
function ownedFiles(out: string): string[] {
  const manifest = join(out, "manifest.json")
  if (!existsSync(manifest)) return []
  try {
    const { files } = JSON.parse(readFileSync(manifest, "utf8")) as { files?: unknown }
    if (!Array.isArray(files)) return []
    return files.filter(
      (path): path is string =>
        typeof path === "string" &&
        path !== "" &&
        !path.startsWith("/") &&
        !path.includes("\\") &&
        !path.split("/").includes(".."),
    )
  } catch {
    return []
  }
}

function removeEmptyParents(out: string, dir: string): void {
  for (let current = dir; current.startsWith(out + sep); current = dirname(current)) {
    if (readdirSync(current).length > 0) return
    rmdirSync(current)
  }
}

function describe(file: OutputFile) {
  const bytes = Buffer.byteLength(file.content, "utf8")
  const sha256 = createHash("sha256").update(file.content).digest("hex")
  return { file: file.path, bytes, sha256 }
}

function sortKeys(record: Readonly<Record<string, string | undefined>>): Record<string, string> {
  return Object.fromEntries(
    Object.entries(record)
      .filter((entry): entry is [string, string] => entry[1] !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : 1)),
  )
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`
}
