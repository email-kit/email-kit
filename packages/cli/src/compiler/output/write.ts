import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmdirSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { dirname, join, relative, sep } from "node:path"

import { EmailKitError } from "@email-kit/core/internal"

import { toPosix } from "../../paths.ts"
import type { OutputFile } from "./index.ts"

/** What writing the output changed, as paths relative to the output folder. */
export interface WriteResult {
  readonly written: readonly string[]
  readonly unchanged: readonly string[]
  readonly deleted: readonly string[]
}

/** How every generated module file starts, and so how email-kit recognises its own folder. */
const SIGNATURE = "// Generated by email-kit"

/** The files that carry the signature: whichever module format was written, and the types. */
const SIGNED = ["index.ts", "index.mjs", "index.d.mts", "messages.d.ts"]

/**
 * Writes the files, skipping unchanged ones, and deletes every other file in the folder: the
 * compiler owns it. Files and folders whose names start with `.`, such as `.gitkeep`, are left
 * alone. A folder that has files but wasn't written by email-kit is refused, so a mistyped `out`
 * can't wipe other code.
 */
export function writeOutput(out: string, files: readonly OutputFile[], label = out): WriteResult {
  const present = filesIn(out)
  if (present.length > 0 && !isGeneratedFolder(out)) {
    throw new EmailKitError(
      "out-not-owned",
      `${label} has files email-kit didn't write. Each compile replaces everything in the ` +
        'output folder, so set "out" to a new or empty folder, or empty this one',
    )
  }
  const next = new Set(files.map((file) => file.path))
  const deleted: string[] = []
  for (const path of present) {
    if (next.has(path)) continue
    const target = resolveIn(out, path)
    rmSync(target, { force: true })
    removeEmptyParents(out, dirname(target))
    deleted.push(path)
  }

  const written: string[] = []
  const unchanged: string[] = []
  for (const file of files) {
    const target = resolveIn(out, file.path)
    if (existsSync(target) && readFileSync(target, "utf8") === file.content) {
      unchanged.push(file.path)
      continue
    }
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, file.content)
    written.push(file.path)
  }
  return { written, unchanged, deleted }
}

/**
 * Whether email-kit wrote the folder: a generated module or `messages.d.ts` in it starts with
 * the "Generated by email-kit" header, or it has a manifest.json with email-kit's signature.
 */
export function isGeneratedFolder(folder: string): boolean {
  for (const name of SIGNED) {
    const file = join(folder, name)
    if (existsSync(file) && readFileSync(file, "utf8").startsWith(SIGNATURE)) return true
  }
  try {
    const manifest = JSON.parse(readFileSync(join(folder, "manifest.json"), "utf8")) as Record<
      string,
      unknown
    >
    return (
      typeof manifest.emailKit === "string" && String(manifest.dialect).startsWith("mustache-core")
    )
  } catch {
    return false
  }
}

/** Every file in the folder, as `/`-separated relative paths, except those under a `.` name. */
function filesIn(out: string): string[] {
  if (!existsSync(out)) return []
  return readdirSync(out, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => toPosix(relative(out, join(entry.parentPath, entry.name))))
    .filter((path) => !path.split("/").some((part) => part.startsWith(".")))
    .sort()
}

/** A `/`-separated path inside the output folder, with the platform's separators. */
function resolveIn(out: string, path: string): string {
  return join(out, ...path.split("/"))
}

/** Removes `dir` and the folders above it while they're empty, stopping at the output folder. */
function removeEmptyParents(out: string, dir: string): void {
  for (let current = dir; current.startsWith(out + sep); current = dirname(current)) {
    if (readdirSync(current).length > 0) return
    rmdirSync(current)
  }
}
