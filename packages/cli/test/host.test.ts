// P1-076 / ADR 0004: with `module: "mjs"`, a tsc-built ESM or CommonJS backend imports the
// compiled emails through `#email-kit`, type-checks against index.d.mts, and runs on plain Node.

import { execFileSync } from "node:child_process"
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join, sep } from "node:path"
import { fileURLToPath } from "node:url"

import { afterAll, describe, expect, it } from "vitest"

import { compile } from "../src/compiler/build.ts"

const FIXTURE = fileURLToPath(new URL("fixtures/project/", import.meta.url))
const TMP = fileURLToPath(new URL(".tmp/host-test/", import.meta.url))
const TSC = join(
  dirname(createRequire(import.meta.url).resolve("typescript/package.json")),
  "bin",
  "tsc",
)

afterAll(() => rmSync(TMP, { recursive: true, force: true }))

async function mjsProject(type: "module" | "commonjs"): Promise<string> {
  mkdirSync(TMP, { recursive: true })
  const dir = mkdtempSync(join(TMP, `${type}-`))
  cpSync(FIXTURE, dir, { recursive: true, filter: (path) => !path.includes(`${sep}compiled`) })
  const config = join(dir, "email-kit.config.ts")
  writeFileSync(
    config,
    readFileSync(config, "utf8").replace("locales:", 'module: "mjs",\n  locales:'),
  )
  await compile({ cwd: dir })
  writeFileSync(
    join(dir, "package.json"),
    JSON.stringify({
      name: "host",
      private: true,
      type,
      imports: { "#email-kit": "./src/email-kit/compiled/index.mjs" },
    }),
  )
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        module: "nodenext",
        target: "es2022",
        strict: true,
        outDir: "dist",
        rootDir: "src",
        types: [],
      },
      files: ["src/server.ts"],
    }),
  )
  writeFileSync(
    join(dir, "src", "server.ts"),
    `import { createEmails } from "#email-kit"

const emails = createEmails({ siteUrl: "https://shop.example" })

const order = {
  customerName: "Ada",
  orderNumber: "A-1042",
  orderUrl: "https://shop.example/orders/A-1042",
  items: [{ name: "Tea", qty: 2 }],
}
// Type-checked, never called: typed from index.d.mts, so a missing field is an error.
export function notCalled() {
  // @ts-expect-error: orderNumber, orderUrl and items are missing
  emails.orderConfirmation.render({ customerName: "Ada" })
}
const email = emails.orderConfirmation.render(order, { locale: "de" })
console.log(email.subject)
`,
  )
  return dir
}

describe.each(["module", "commonjs"] as const)("a tsc-built %s backend", (type) => {
  it("type-checks, builds and renders through #email-kit", async () => {
    const dir = await mjsProject(type)
    execFileSync(process.execPath, [TSC, "-p", "tsconfig.json"], { cwd: dir, stdio: "pipe" })
    const output = execFileSync(process.execPath, ["dist/server.js"], {
      cwd: dir,
      encoding: "utf8",
    })
    expect(output.trim()).toBe("Bestellung A-1042 bestätigt")
  })
})

describe('module: "mjs"', () => {
  it("writes index.mjs and index.d.mts instead of index.ts", async () => {
    const dir = await mjsProject("module")
    const compiled = join(dir, "src", "email-kit", "compiled")
    const manifest = JSON.parse(readFileSync(join(compiled, "manifest.json"), "utf8")) as {
      files: string[]
    }
    expect(manifest.files.filter((file) => file.startsWith("index."))).toEqual([
      "index.d.mts",
      "index.mjs",
    ])
    const js = readFileSync(join(compiled, "index.mjs"), "utf8")
    const dts = readFileSync(join(compiled, "index.d.mts"), "utf8")
    for (const file of [js, dts])
      expect(file).toMatch(/^\/\/ Generated by email-kit .*Do not edit:/)
    expect(js).not.toMatch(/\binterface\b|: string\b|as const/)
    expect(dts).toContain("export declare function createEmails(context: EmailContext): Emails;")
    expect(dts).toContain(
      'readonly orderConfirmation: EmailTemplate<"order-confirmation", OrderConfirmationData>',
    )
  })
})
