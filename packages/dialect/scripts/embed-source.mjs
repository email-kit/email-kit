// Writes dist/source.js: the renderer and the module runtime as TypeScript source in one string,

import { readdirSync, readFileSync, writeFileSync } from "node:fs"

const MARKER = "// --- inlined into generated modules from here ---\n"

const RUNTIME_FILES = [
  "runtime/types.ts",
  "runtime/shared.ts",
  "runtime/locale.ts",
  "runtime/validate.ts",
  "runtime/project.ts",
  "runtime/plurals.ts",
  "runtime/context.ts",
  "runtime/template.ts",
]

const unlisted = readdirSync(new URL("../src/runtime/", import.meta.url))
  .map((name) => `runtime/${name}`)
  .filter((file) => !RUNTIME_FILES.includes(file))
if (unlisted.length > 0)
  throw new Error(`add ${unlisted.join(", ")} to RUNTIME_FILES in scripts/embed-source.mjs`)

function inlinable(file) {
  const full = readFileSync(new URL(`../src/${file}`, import.meta.url), "utf8")
  const start = full.indexOf(MARKER)
  if (start === -1) throw new Error(`src/${file} has no "${MARKER.trim()}" line`)
  return full
    .slice(start + MARKER.length)
    .replace(/^export \{[^}]*\}\n?/gm, "")
    .replace(/^export (?=(?:const|function|class|type|interface) )/gm, "")
    .trim()
}

const source = `${["index.ts", ...RUNTIME_FILES].map(inlinable).join("\n\n")}\n`
if (/^(?:import|export) /m.test(source))
  throw new Error("the inlined source still has an import or export")

writeFileSync(
  new URL("../dist/source.js", import.meta.url),
  `// Generated by scripts/embed-source.mjs.\nexport const source = ${JSON.stringify(source)}\n`,
)
writeFileSync(
  new URL("../dist/source.d.ts", import.meta.url),
  "/** The renderer and module runtime as TypeScript source, without exports. */\nexport declare const source: string\n",
)
